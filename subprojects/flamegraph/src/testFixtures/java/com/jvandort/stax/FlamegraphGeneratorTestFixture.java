package com.jvandort.stax;

import java.io.BufferedInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Base64;
import java.util.Collection;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;
import java.util.zip.Inflater;
import java.util.zip.InflaterInputStream;

/**
 * Test fixtures useful for verifying content of files generated by {@link FlamegraphGenerator}.
 */
public class FlamegraphGeneratorTestFixture {

    private static final Base64.Decoder DECODER = Base64.getDecoder();

    private static final byte[] NAMES_TEMPLATE_TAG =
        "<template id=\"embedded-file-names\">".getBytes(StandardCharsets.UTF_8);

    /**
     * Assert that all given embedded files, and no others, are embedded in the given flamegraph HTML file.
     *
     * @param flamegraphHtml path to the flamegraph HTML file
     * @param embeddedFiles paths to the files to check for
     */
    public static void assertHasEmbeddedFiles(Path flamegraphHtml, Collection<Path> embeddedFiles) {
        assertHasEmbeddedFiles(flamegraphHtml, embeddedFiles, true);
    }

    /**
     * Asserts that all given embedded files are embedded in the given flamegraph HTML file.
     * <p>
     * When {@code strict} is true, the flamegraph must contain exactly the given embedded
     * files and no others. When {@code strict} is false, the flamegraph may contain
     * additional embedded files beyond those specified, but all given files must be present with
     * matching content.
     *
     * @param flamegraphHtml path to the flamegraph HTML file
     * @param embeddedFiles paths to the embedded files to check for
     * @param strict if true, no extra embedded files are permitted. If false, extra files are allowed
     * @throws AssertionError if a file is missing, unexpected, or embedded with different content
     */
    public static void assertHasEmbeddedFiles(Path flamegraphHtml, Collection<Path> embeddedFiles, boolean strict) {
        List<String> embeddedNames = getEmbeddedFileNames(flamegraphHtml);
        Set<String> expectedNames = embeddedFiles.stream()
            .map(x -> x.getFileName().toString())
            .collect(Collectors.toCollection(LinkedHashSet::new));

        List<String> missing = new ArrayList<>(expectedNames);
        missing.removeAll(embeddedNames);
        if (!missing.isEmpty()) {
            throw new AssertionError("Expected files " + missing + " to be embedded, but found " + embeddedNames);
        }
        if (strict) {
            List<String> unexpected = new ArrayList<>(embeddedNames);
            unexpected.removeAll(expectedNames);
            if (!unexpected.isEmpty()) {
                throw new AssertionError("Found unexpected files " + unexpected + " embedded. Expected only " + expectedNames);
            }
        }

        for (Path expectedFile : embeddedFiles) {
            String name = expectedFile.getFileName().toString();
            if (!embeddedFileHasContent(flamegraphHtml, embeddedNames.indexOf(name), expectedFile)) {
                throw new AssertionError("Embedded file " + name + " does not match expected content");
            }
        }
    }

    /**
     * Returns the names of the files embedded in the given flamegraph HTML file,
     * in the order they were embedded.
     *
     * @param flamegraphHtml path to the flamegraph HTML file
     *
     * @return the embedded file names, or an empty list if none are found
     */
    private static List<String> getEmbeddedFileNames(Path flamegraphHtml) {
        try (InputStream input = new BufferedInputStream(Files.newInputStream(flamegraphHtml))) {
            if (!skipToLineStartingWith(input, NAMES_TEMPLATE_TAG)) {
                return List.of();
            }
            String namesBase64 = new String(new ElementTextInputStream(input).readAllBytes(), StandardCharsets.US_ASCII);
            if (namesBase64.isEmpty()) {
                return List.of();
            }
            return Arrays.stream(namesBase64.split(","))
                .map(s -> new String(DECODER.decode(s), StandardCharsets.UTF_8))
                .collect(Collectors.toList());
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * Returns true if the files embedded at {@code index} in the given flamegraph HTML file
     * matches the content of {@code content}. The data is Base64-encoded raw deflate, as
     * {@link FlamegraphGenerator} writes it.
     *
     * @param flamegraphHtml path to the flamegraph HTML file
     * @param index index of the embedded entry to check
     * @param content path to the original file to compare against
     *
     * @return true if the embedded data equals the content of {@code content}
     */
    private static boolean embeddedFileHasContent(Path flamegraphHtml, int index, Path content) {
        byte[] templateTag = ("<template id=\"embedded-file-" + index + "\">").getBytes(StandardCharsets.UTF_8);
        try (InputStream input = new BufferedInputStream(Files.newInputStream(flamegraphHtml))) {
            if (!skipToLineStartingWith(input, templateTag)) {
                return false;
            }
            Inflater inflater = new Inflater(true); // Raw deflate. No zlib header or checksum.
            try (InputStream inflated = new InflaterInputStream(DECODER.wrap(new ElementTextInputStream(input)), inflater);
                 InputStream expected = new BufferedInputStream(Files.newInputStream(content))
            ) {
                return streamsEqual(inflated, expected);
            } finally {
                inflater.end();
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * Reads {@code input} up to the end of {@code prefix}, at the start of the first line that
     * begins with it.
     *
     * @return false if no line begins with {@code prefix}
     */
    private static boolean skipToLineStartingWith(InputStream input, byte[] prefix) throws IOException {
        int matched = 0;
        while (matched < prefix.length) {
            int b = input.read();
            if (b == -1) {
                return false;
            }
            if (b == (prefix[matched] & 0xff)) {
                matched++;
                continue;
            }
            matched = 0;
            while (b != '\n') {
                b = input.read();
                if (b == -1) {
                    return false;
                }
            }
        }
        return true;
    }

    private static boolean streamsEqual(InputStream a, InputStream b) throws IOException {
        byte[] bufA = new byte[8192];
        byte[] bufB = new byte[8192];
        while (true) {
            int nA = a.readNBytes(bufA, 0, bufA.length);
            int nB = b.readNBytes(bufB, 0, bufB.length);
            if (nA != nB) {
                return false;
            }
            if (nA == 0) {
                return true;
            }
            if (!Arrays.equals(bufA, 0, nA, bufB, 0, nB)) {
                return false;
            }
        }
    }

    /**
     * Wraps an {@link InputStream} positioned just after an element's opening tag, reading its
     * text content up to the {@code <} of the next tag, without consuming the rest of the
     * underlying stream.
     */
    private static class ElementTextInputStream extends InputStream {

        private final InputStream delegate;
        private boolean done;

        ElementTextInputStream(InputStream delegate) {
            this.delegate = delegate;
        }

        @Override
        public int read() throws IOException {
            if (done) {
                return -1;
            }
            int b = delegate.read();
            if (b == -1 || b == '<') {
                done = true;
                return -1;
            }
            return b;
        }

        @Override
        public int read(byte[] buf, int off, int len) throws IOException {
            if (done) {
                return -1;
            }
            int count = 0;
            while (count < len) {
                int b = read();
                if (b == -1) {
                    break;
                }
                buf[off + count++] = (byte) b;
            }
            return count == 0 ? -1 : count;
        }

        @Override
        public void close() {
            // Do not close the delegate
        }

    }

}
